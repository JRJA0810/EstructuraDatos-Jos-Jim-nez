    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    
    Producto productoTemp = new Producto(
    txtNombre.getText(), 
    txtMarca.getText(),
    Double.parseDouble( txtPrecio.getText() ),
    Integer.parseInt (txtStock.getText())
    );
    
    listaProductos.add(productoTemp);
    this.actualizarLista();
    
    System.out.println(listaProductos.toString());
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
    
    int indice = Integer.parseInt( txtIndice.getText() );
    listaProductos.remove(indice);
    actualizarLista();    
                               
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    
        int indice = Integer.parseInt(txtEditar.getText());
        Producto productoEdit = listaProductos.get(indice);
        
        if (!txtNombre.getText().trim().isEmpty()) {
    productoEdit.setNombre(txtNombre.getText().trim());
}
if (!txtMarca.getText().trim().isEmpty()) {
    productoEdit.setMarca(txtMarca.getText().trim()); // Corregido: txtMarca
}
if (!txtPrecio.getText().trim().isEmpty()) {
    productoEdit.setPrecio(Double.parseDouble(txtPrecio.getText().trim())); // Corregido: txtPrecio
}
if (!txtStock.getText().trim().isEmpty()) {
    productoEdit.setStock(Integer.parseInt(txtStock.getText().trim())); // Corregido: txtStock
}
        listaProductos.set(indice, productoEdit);
        actualizarLista();
        
        
    }//GEN-LAST:event_jButton2ActionPerformed


