    public void actualizarLista(){
        txaLista.setText("");
        listaTexto ="";
        
        //Llenamos la lista
        for(Producto p : listaProductos){
            listaTexto+= p.getNombre() + "$" + 
            p.getPrecio() +" (" + p.getStock() + ")\n";
        }
        
        //Rellenar campos
        txaLista.setText(listaTexto);
        txtNombre.setText("");
        txtMarca.setText("");
        txtPrecio.setText("");
        txtStock.setText("");
     
        //Focus en nombe para volver a empezar
        txtNombre.requestFocusInWindow();
        
    }


